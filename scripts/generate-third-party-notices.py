#!/usr/bin/env python
"""Assemble THIRD-PARTY-NOTICES.md from the artifacts that actually ship.

Why this exists rather than a hand-maintained list, or a list derived from
the SBOM's licence texts:

The CycloneDX SBOM this build ships embeds no licence text at all -
`cyclonedx-maven-plugin` leaves `includeLicenseText` off by default and this
project does not turn it on. The SBOM names every component's licence, which
is what it is for; it is not an attribution file.

Turning that option on would not fix it either. An SBOM generated with
`includeLicenseText=true` during this project's licensing review did embed
text for 112 of 115 components - and 109 of the 117 texts were the
*canonical template* of the licence, Apache-2.0's appendix still reading
"Copyright [yyyy] [name of copyright owner]", MIT's still reading
"Copyright (c) <year> <copyright holders>". A template is the licence, not
the attribution notice the licence asks a distributor to preserve. Only 8
carried concrete terms, and those were the copyleft licences, which have no
fill-in appendix.

The real notices are inside the jars. Apache-2.0 section 4(d) requires
preserving a NOTICE file if the distributed work has one, and upstream
projects put it at META-INF/NOTICE; BSD- and MIT-licensed projects instead
put their copyright line in META-INF/LICENSE, where it is the notice the
licence requires a distributor to retain. So this script opens every jar the
repackaged application actually contains and copies out what is really
there - both kinds of file, judged by whether the content states a real
copyright rather than by its name - instead of restating what a licence
template says.

It reads the shipped artifact, not the dependency tree, deliberately: the
dependency tree is what Maven resolved, the jar is what reaches a user. The
IBM driver is excluded from that jar (ADR 0048), so it correctly does not
appear here.

It is also a completeness gate, not only an extractor. A 2026-10-10
review made the distinction: --check used to confirm that the file could be
regenerated byte-for-byte, which says nothing about whether every shipped
component's licence obligation is actually discharged. Six MIT components,
one BSD-3-Clause component and the two EPL Logback artifacts shipped with no
licence material of their own, and nothing failed. Now the required material
per component is derived from its elected licence, satisfied either from the
artifact or from the version-pinned supplement in
third-party-licenses/MANIFEST.json, and an unsatisfied component fails.

Usage: python scripts/generate-third-party-notices.py [--check]
  --check  exit 1 if THIRD-PARTY-NOTICES.md is out of date OR if any shipped
           component lacks its required licence material
"""

import hashlib
import io
import json
import os
import re
import sys
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTPUT = os.path.join(ROOT, "THIRD-PARTY-NOTICES.md")
SBOM = os.path.join(ROOT, "target", "classes", "META-INF", "sbom", "application.cdx.json")
SUPPLEMENT_DIR = os.path.join(ROOT, "third-party-licenses")
SUPPLEMENT = os.path.join(SUPPLEMENT_DIR, "MANIFEST.json")

# What each licence actually requires of someone redistributing a binary.
# None means the licence imposes no attribution or licence-delivery
# condition, which is a finding worth recording rather than an absence.
REQUIREMENT = {
    "Apache-2.0": "a copy of the licence, plus any NOTICE the artifact carries",
    "MIT": "the copyright notice and the permission notice",
    "MIT-0": None,
    "BSD-2-Clause": "the copyright notice, the conditions and the disclaimer",
    "BSD-3-Clause": "the copyright notice, the conditions and the disclaimer",
    "BSD-4-Clause": "the copyright notice, the conditions, the disclaimer and the advertising acknowledgement",
    "EPL-2.0": "a copy of the licence, plus a source-availability statement (section 3.1(a))",
    "LGPL-2.1-only": "a copy of the licence, plus source availability",
    "GPL-2.0-with-classpath-exception": "a copy of the licence, plus source availability",
    "CC0-1.0": None,
    "Public Domain": None,
}

NOTICE_ENTRY = re.compile(r"(^|/)NOTICE([.-][^/]*)?$", re.I)
LICENSE_ENTRY = re.compile(r"(^|/)(LICEN[CS]E|COPYING)([.-][^/]*)?$", re.I)

# A concrete copyright line: "Copyright <something>" where the something is
# not the licence template's own placeholder. Apache-2.0's appendix reads
# "Copyright [yyyy] [name of copyright owner]"; MIT's reads
# "Copyright (c) <year> <copyright holders>". Those are the licence, not an
# attribution, and pulling them in would re-import exactly the template text
# this script exists to avoid.
PLACEHOLDER = re.compile(
    r"\[yyyy\]|\{yyyy\}|<year>|\[year\]|<copyright holders?>"
    r"|\[name of copyright owner\]|<name of author>|<owner>|<OWNER>"
    r"|<ORGANIZATION>|\[fullname\]|<insert",
    re.I,
)
# A real copyright statement, as opposed to prose that merely contains the
# word. Requires the shape an actual notice has: "Copyright", an optional
# (c)/©, a LITERAL four-digit year (possibly a range or list), and then a
# holder name of some substance.
#
# The literal year is what does the work. Apache-2.0's appendix reads
# "Copyright [yyyy] [name of copyright owner]" - no four-digit year, so it
# cannot match. Nor can the body text of a licence, which talks ABOUT
# copyright ("the original copyright holder", "Copyright Notice") without
# ever stating one. An earlier, looser version of this function accepted any
# line containing "copyright" that was not itself a placeholder, and let the
# whole Apache-2.0 text through on lines like "copyright owner or entity" -
# caught by checking the generated file for template text rather than
# trusting the rule.
# Two shapes, because a real notice does not have to carry a year. The
# 2026-10-10 review was right that discarding year-less attribution is
# acceptable for de-duplicating text but not for preserving a notice:
# "Copyright The Netty Project" is attribution and must survive.
COPYRIGHT_STATEMENT = re.compile(
    r"copyright\s*(?:\([cC]\)|©|&copy;)?\s*"
    r"(?:"
    r"(?:19|20)\d{2}"                      # a literal year ...
    r"(?:\s*[-,–]\s*(?:(?:19|20)\d{2}|present))*"
    r"[\s,]+\S"                            # ... then a name
    r"|"
    r"(?:the\s+)?[A-Z][\w.&-]*(?:\s+[\w.&-]+){0,6}"   # or a name, no year
    r")",
    re.I,
)


def concrete_copyright(text):
    """True if the text states a real copyright, not a placeholder one.

    Decides whether an embedded LICENSE file is worth reproducing. For an
    Apache-2.0 component, META-INF/LICENSE.txt is just the Apache text and
    adds nothing. For a BSD- or MIT-licensed component, that same file is
    where the actual copyright holder is named - and under those licences the
    copyright notice IS the thing a distributor must retain. So the rule is
    about content, not filename.
    """
    for match in COPYRIGHT_STATEMENT.finditer(text):
        line_start = text.rfind("\n", 0, match.start()) + 1
        line_end = text.find("\n", match.end())
        line = text[line_start: line_end if line_end != -1 else len(text)]
        if not PLACEHOLDER.search(line):
            return True
    return False


def find_jar():
    target = os.path.join(ROOT, "target")
    if not os.path.isdir(target):
        return None
    for name in sorted(os.listdir(target)):
        if (
            name.startswith("db2-mcp-server-")
            and name.endswith(".jar")
            and "sources" not in name
            and "javadoc" not in name
        ):
            return os.path.join(target, name)
    return None


def sbom_licences():
    """Map 'artifactId-version.jar' -> (coordinates, [licence ids])."""
    if not os.path.exists(SBOM):
        return {}
    with io.open(SBOM, encoding="utf-8") as fh:
        bom = json.load(fh)
    out = {}
    for comp in bom.get("components", []):
        name, version = comp.get("name"), comp.get("version")
        if not name or not version:
            continue
        ids = []
        for entry in comp.get("licenses", []):
            lic = entry.get("license", {})
            ids.append(lic.get("id") or lic.get("name") or "declared, unnamed")
            # NB: entry may instead be {"expression": ...}
            if not lic and entry.get("expression"):
                ids[-1] = entry["expression"]
        out["%s-%s.jar" % (name, version)] = (
            "%s:%s:%s" % (comp.get("group", "?"), name, version),
            ids or ["none declared"],
        )
    return out


def sbom_text_stats():
    """(components, how many carry an embedded licence text) from the SBOM."""
    if not os.path.exists(SBOM):
        return 0, 0
    with io.open(SBOM, encoding="utf-8") as fh:
        bom = json.load(fh)
    comps = bom.get("components", [])
    with_text = sum(
        1
        for c in comps
        if any("text" in e.get("license", {}) for e in c.get("licenses", []))
    )
    return len(comps), with_text


def load_supplement():
    """The version-pinned upstream material, or an empty shell if absent."""
    if not os.path.exists(SUPPLEMENT):
        return {}
    with io.open(SUPPLEMENT, encoding="utf-8") as fh:
        sup = json.load(fh)
    for name, entry in sup.get("licence_texts", {}).items():
        path = os.path.join(SUPPLEMENT_DIR, name)
        with open(path, "rb") as fh:
            actual = hashlib.sha256(fh.read()).hexdigest()
        if actual != entry.get("sha256"):
            raise ValueError("licence supplement checksum mismatch: %s" % name)
    return sup


def sufficient_material(licence, bodies):
    """Structural material check; this is not a legal-compliance verdict."""
    normalized = " ".join(" ".join(bodies).lower().split())
    if licence == "Apache-2.0":
        return "apache license" in normalized and "version 2.0" in normalized
    if licence == "EPL-2.0":
        return ("eclipse public license" in normalized and
                os.path.isfile(os.path.join(ROOT, "SOURCE-AVAILABILITY.md")))
    if licence == "MIT":
        return all(s in normalized for s in (
            "copyright", "permission is hereby granted, free of charge",
            "permission notice shall be included", "without warranty"))
    if licence in ("BSD-2-Clause", "BSD-3-Clause"):
        required = ["copyright", "redistributions of source code",
                    "redistributions in binary form", "disclaimer",
                    "in no event", "damage"]
        if licence == "BSD-3-Clause":
            required.append("may be used to endorse or promote")
        return all(s in normalized for s in required)
    return False


def verify_embedded_legal(jar_path):
    """A fresh checkout passing --check must match the released jar bytes."""
    names = ["LICENSE", "NOTICE", "LICENSE-HISTORY.md",
             "LICENSE-ELECTIONS.md", "ENTERPRISE-EVALUATION.md",
             "SOURCE-AVAILABILITY.md", "THIRD-PARTY-NOTICES.md",
             "LICENSES/Apache-2.0.txt"]
    names += ["third-party-licenses/" + n
              for n in sorted(os.listdir(SUPPLEMENT_DIR))
              if os.path.isfile(os.path.join(SUPPLEMENT_DIR, n))]
    with zipfile.ZipFile(jar_path) as archive:
        for name in names:
            with open(os.path.join(ROOT, name), "rb") as fh:
                expected = fh.read()
            try:
                embedded = archive.read("META-INF/legal/" + name)
            except KeyError:
                raise ValueError("missing packaged legal file: %s" % name)
            if embedded != expected:
                raise ValueError("stale packaged legal file: %s; rebuild the jar" % name)


def supplement_index(sup):
    """coordinates -> [(filename, text, entry)] from the supplement."""
    index = {}
    texts = sup.get("licence_texts", {})

    def add(coords, fname):
        meta = texts.get(fname)
        if meta is None:
            return
        path = os.path.join(SUPPLEMENT_DIR, fname)
        if not os.path.exists(path):
            return
        with io.open(path, encoding="utf-8") as fh:
            body = fh.read().strip()
        index.setdefault(coords, []).append((fname, body, meta))

    for fname, meta in texts.items():
        for coords in meta.get("covers", []) or []:
            add(coords, fname)

    return index


def shared_texts(sup):
    """licence id -> (filename, text) that discharges it for any component."""
    out = {}
    for licence, fname in (sup.get("shared_by_licence", {}) or {}).items():
        if licence.startswith("_"):
            continue
        path = os.path.join(SUPPLEMENT_DIR, fname)
        if not os.path.exists(path):
            continue
        with io.open(path, encoding="utf-8") as fh:
            out[licence] = (fname, fh.read().strip())
    return out


def requirement_for(coords, declared, elections):
    """What this component needs, after applying any recorded election."""
    ids = [i.strip() for i in declared.split(" OR ")]
    elected = elections.get(coords)
    if elected:
        chosen = elected
    elif len(ids) == 1:
        chosen = ids[0]
    else:
        return None, "unelected", ids
    return REQUIREMENT.get(chosen, "unknown licence - review by hand"), chosen, ids


def collect(jar_path):
    """Return (components, notices, compliance) read out of the shipped jar.

    `compliance` is one record per shipped library: what its elected licence
    requires, and whether that is satisfied from the artifact itself, from
    the version-pinned supplement, or not at all. The last case is what
    --check fails on.
    """
    archive = zipfile.ZipFile(jar_path)
    libs = sorted(
        n for n in archive.namelist()
        if n.startswith("BOOT-INF/lib/") and n.endswith(".jar")
    )
    licences = sbom_licences()
    sup = load_supplement()
    for base, entry in sup.get("extra_components", {}).items():
        licences.setdefault(base, (entry["coordinates"], entry["licenses"]))
    sup_index = supplement_index(sup)
    sup_shared = shared_texts(sup)
    elections = {k: v for k, v in sup.get("elections", {}).items()
                 if not k.startswith("_")}
    exempt = {k for k in sup.get("no_material_required", {})
              if not k.startswith("_")}
    components, notices, compliance = [], {}, []

    for lib in libs:
        base = os.path.basename(lib)
        coords, ids = licences.get(base, (base, ["not in SBOM"]))
        texts = []
        try:
            inner = zipfile.ZipFile(io.BytesIO(archive.read(lib)))
        except Exception as exc:                      # noqa: BLE001
            components.append((base, coords, ids, "unreadable: %s" % exc))
            compliance.append((base, coords, "unreadable", "readable artifact",
                               "BLOCKED", "cannot inspect the bundled archive"))
            continue
        skipped_licence_only = False
        for entry in inner.namelist():
            if entry.endswith("/"):
                continue
            is_notice = bool(NOTICE_ENTRY.search(entry))
            is_licence = bool(LICENSE_ENTRY.search(entry))
            if not (is_notice or is_licence):
                continue
            try:
                text = inner.read(entry).decode("utf-8", "replace").strip()
            except Exception:                          # noqa: BLE001
                continue
            if not text:
                continue
            # NOTICE files are attribution by definition. LICENSE files are
            # included only when they actually name a copyright holder - see
            # concrete_copyright().
            if is_notice or concrete_copyright(text):
                texts.append((entry, text))
            elif is_licence:
                skipped_licence_only = True
        if texts:
            for entry, text in texts:
                digest = hashlib.sha256(text.encode("utf-8")).hexdigest()
                notices.setdefault(digest, {"text": text, "from": []})
                notices[digest]["from"].append("%s (%s)" % (base, entry))
            components.append((base, coords, ids, "notice included below"))
        elif skipped_licence_only:
            components.append(
                (base, coords, ids,
                 "licence text only, no attribution to preserve")
            )
        else:
            components.append((base, coords, ids, "no notice file in the artifact"))

        # --- compliance record -------------------------------------------
        declared = " OR ".join(ids)
        required, elected, _ = requirement_for(coords, declared, elections)
        bodies = [body for _entry, body in texts]
        bodies += [body for _name, body, _meta in sup_index.get(coords, [])]
        if elected in sup_shared:
            bodies.append(sup_shared[elected][1])
        from_supplement = [f for f, _b, _m in sup_index.get(coords, [])]
        if elected in sup_shared and sup_shared[elected][0] not in from_supplement:
            from_supplement.append(sup_shared[elected][0])
        if elected not in REQUIREMENT and elected != "unelected":
            state, why = "BLOCKED", "unknown licence; record reviewed provenance"
        elif coords in exempt and required is not None:
            state, why = "BLOCKED", "invalid exemption for a licence requiring material"
        elif coords in exempt:
            state, why = "exempt", sup["no_material_required"][coords]
        elif required is None and elected == "unelected":
            state, why = "BLOCKED", (
                "multi-licensed and no election is recorded, so what is "
                "required cannot be determined")
        elif required is None:
            state, why = "none required", "%s imposes no such condition" % elected
        elif not sufficient_material(elected, bodies):
            state, why = "BLOCKED", "required licence material or source statement is missing"
        elif texts and from_supplement:
            state, why = "satisfied", "artifact material and supplement"
        elif texts:
            state, why = "satisfied", "material carried by the artifact"
        elif from_supplement:
            state, why = "satisfied", "supplement: %s" % ", ".join(from_supplement)
        else:
            state, why = "BLOCKED", "no material from the artifact or the supplement"
        compliance.append((base, coords, elected, required, state, why))

    archive.close()
    return components, notices, compliance


